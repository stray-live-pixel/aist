/**
 * Что это: максимальное время ожидания socket после запуска daemon.
 * Зачем нужно: extension не должен бесконечно ждать неудачный старт процесса.
 * Какую проблему решает: пользователь быстро получает понятную ошибку запуска.
 */
export const CONNECT_TIMEOUT_MS = 8000;

/**
 * Что это: период polling socket во время старта daemon.
 * Зачем нужно: daemon может поднять socket не мгновенно после spawn.
 * Какую проблему решает: подключение остаётся быстрым без busy loop.
 */
export const CONNECT_POLL_MS = 150;

/**
 * Что это: верхняя граница backoff для автоматического restart daemon.
 * Зачем нужно: при падениях daemon extension не запускает процесс слишком часто.
 * Какую проблему решает: защита от бесконечного crash-loop с высокой нагрузкой.
 */
export const MAX_RESTART_DELAY_MS = 5000;
