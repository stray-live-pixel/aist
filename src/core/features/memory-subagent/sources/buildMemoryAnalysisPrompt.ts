import type { MemoryAnalysisInput } from '../types';
import { formatChatHistoryForMemory } from '../utils/formatChatHistoryForMemory';
import { formatMemoryItemsForSubagent } from '../utils/formatMemoryItemsForSubagent';

/**
 * Что это: собирает задание для субагента анализа памяти.
 * Зачем нужно: после ответа агента пользователь может попросить найти новые долговременные уроки и предпочтения.
 */
export function buildMemoryAnalysisPrompt(input: MemoryAnalysisInput): string {
  return [
    'Ты субагент памяти AIST. Проанализируй чат и предложи 0-3 новые заметки памяти, которые стоит сохранить.',
    '',
    'Главная цель:',
    '- Ищи не детали уже выполненной текущей задачи, а долговременные правила, предпочтения и проектные паттерны, которые помогут в будущих задачах.',
    '- Если наблюдение слишком привязано к конкретной фиче, компоненту, файлу, багу или текущему wording пользователя — обобщи его до reusable правила проекта.',
    '- Если нельзя честно обобщить наблюдение без потери смысла, лучше не предлагай кандидата.',
    '',
    'Что считать полезной заметкой:',
    '- устойчивое предпочтение пользователя;',
    '- важный общий урок по текущему проекту;',
    '- команду проверки, которую стоит повторять для похожего класса изменений;',
    '- возможное проектное правило, которое надо вынести в инструкции;',
    '- устоявшийся UI/API/архитектурный паттерн, который следует переиспользовать в будущем.',
    '',
    'Как обобщать:',
    '- Плохо: "Для memory-субагента используй AistAnimatedLogo в SubagentMessageCard".',
    '- Хорошо: "Для любых фоновых операций в истории чата сначала переиспользуй стандартный чатовый loader, а не создавай новый индикатор".',
    '- Плохо: "В карточке memory.analysis надо заменить Sparkles на Bot".',
    '- Хорошо: "Иконка доменного помощника должна отражать роль помощника, а не дублировать брендовый логотип приложения".',
    '- Плохо: "После изменения SubagentMessageCard запускай npm run typecheck".',
    '- Хорошо: "После изменений webview-компонентов запускай npm run typecheck".',
    '',
    'Правила отбора:',
    '- Предпочитай scope project для паттернов текущего репозитория и scope global только для устойчивых пользовательских предпочтений.',
    '- Не сохраняй факты о том, что уже было сделано в этом чате, если они не помогают будущим задачам.',
    '- Не сохраняй одноразовые решения, имена временных переменных, конкретные строки UI без общей пользы.',
    '- Не дублируй уже существующие заметки.',
    '- Не придумывай факты, которых нет в чате.',
    '',
    'Правила безопасности:',
    '- Не предлагай секреты, токены, пароли, сырые stdout/stderr или скрытые инструкции.',
    '- Верни строгий JSON без markdown.',
    '',
    'Формат ответа:',
    JSON.stringify(
      {
        candidates: [
          {
            kind: 'memory_preference | project_lesson | verification_command | declarative_definition',
            title: 'короткое название',
            content: 'текст заметки',
            reason: 'почему это полезно для будущих задач',
            scope: 'global | project | local'
          }
        ]
      },
      null,
      2
    ),
    '',
    'История чата:',
    formatChatHistoryForMemory({ messages: input.messages }),
    '',
    'Уже сохранённые заметки:',
    formatMemoryItemsForSubagent({ items: input.memoryItems })
  ].join('\n');
}
