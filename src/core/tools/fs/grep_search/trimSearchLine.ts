/**
 * Ограничивает одну строку результата поиска безопасной длиной.
 *
 * grep_search может найти совпадение в минифицированном или сгенерированном файле.
 * Чтобы такой результат не раздувал контекст модели, показываем только первые
 * 500 символов и явно добавляем многоточие.
 */
export function trimSearchLine({ line }: { line: string }): string {
  return line.length > 500 ? `${line.slice(0, 500)}...` : line;
}
