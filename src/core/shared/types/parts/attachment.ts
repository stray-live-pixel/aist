/**
 * Что это: тип пользовательского вложения, которое Composer отправляет агенту вместе с prompt.
 * Зачем нужно: изображения и файлы проходят через webview, daemon и runtime в одном формате без разных источников правды.
 * Какую продуктовую проблему решает: пользователь может попросить модель проанализировать скриншот, документ или текстовый файл прямо из Composer.
 */
export type AgentAttachment = {
  /** Стабильный идентификатор вложения внутри одного пользовательского сообщения. */
  id: string;
  /** Отображаемое имя файла, чтобы UI и модель понимали, какой артефакт анализируется. */
  name: string;
  /** MIME-тип из browser File API или безопасный fallback application/octet-stream. */
  mimeType: string;
  /** Размер исходного файла в байтах для UI, диагностики и будущих лимитов. */
  size: number;
  /** Продуктовый тип вложения: image отправляется мультимодально, file — как текст/метаданные. */
  kind: 'image' | 'file';
  /** Data URL нужен для vision-моделей; для обычных файлов может отсутствовать, чтобы не раздувать историю. */
  dataUrl?: string;
  /** Текстовое содержимое файла, если browser смог безопасно прочитать его как текст. */
  text?: string;
};
