import type { ModelProvider } from '../../shared/types/types';

/**
 * Что это: пользовательский профиль доступа к конкретному AI-провайдеру.
 * Зачем нужно: корпоративные пользователи часто ходят к тому же провайдеру через разные endpoint/proxy,
 * поэтому профиль отделяет сетевой маршрут от model id и позволяет безопасно дублировать провайдера.
 */
export type ProviderProfile = {
  /** Стабильный id профиля; хранится в настройках и может использоваться в model id в следующих итерациях. */
  id: string;
  /** Человекочитаемое имя, например openrouter-work или openrouter-pet-projects. */
  name: string;
  /** Базовый провайдер, чью схему payload/auth использует профиль. */
  provider: ModelProvider;
  /** Кастомный endpoint для chat/responses запросов; пустое значение означает стандартный endpoint провайдера. */
  endpoint: string;
  /** HTTP(S) proxy host, через который должен идти запрос к endpoint; пустое значение означает прямой запрос. */
  proxyHost: string;
  /** Системный профиль нельзя удалить: он гарантирует обратную совместимость старых настроек. */
  builtIn: boolean;
};
