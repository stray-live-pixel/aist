import type { AgentMode, AgentModeId } from '../../types';

/**
 * Что это: публичные props выпадающего списка режимов агента.
 * Зачем нужно: компонент отправляет IPC-команды сам, поэтому наружу передаются только данные состояния и опциональный className для внешнего sizing-контейнера.
 */
export type AgentModeSelectProps = {
  /** Доступные режимы агента в порядке отображения. */
  modes: AgentMode[];
  /** Идентификатор активного режима; может ссылаться на режим, которого уже нет в списке, тогда показываем id как fallback. */
  activeId: AgentModeId;
  /** Внешний класс допускается только для layout родителя, внутренние стили живут в module.scss. */
  className?: string;
};
