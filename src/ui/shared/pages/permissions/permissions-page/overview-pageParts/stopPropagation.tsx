import type { MouseEvent } from 'react';

/**
 * Что это: останавливает закрытие модалки при клике внутри её поверхности.
 * Зачем нужно: backdrop закрывает диалог, но взаимодействие с текстом и кнопками внутри не должно его закрывать.
 * Какую продуктовую проблему решает: пользователь спокойно читает пояснения и полный текст инструкции без случайного закрытия.
 */
export function stopPropagation(event: MouseEvent) {
  event.stopPropagation();
}
