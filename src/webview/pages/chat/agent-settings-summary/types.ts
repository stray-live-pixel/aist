import type { useI18n } from '../../../shared/i18n';

/**
 * Что это: тип функции перевода webview.
 * Зачем нужно: вынесенные hooks получают t из компонента, но не зависят от React-контекста напрямую.
 * Какую проблему решает: маленькие сценарные файлы остаются типобезопасными и независимыми.
 */
export type Translate = ReturnType<typeof useI18n>['t'];
