/**
 * Что это: вложение, выбранное пользователем в Composer webview.
 * Зачем нужно: UI, IPC и карточка сообщения используют один контракт для изображений и файлов.
 * Какую продуктовую проблему решает: пользователь видит, какие файлы уйдут модели, а backend получает те же данные без преобразований в разных местах.
 */
export type AgentAttachment = {
  /** Стабильный идентификатор вложения внутри одного сообщения. */
  id: string;
  /** Имя файла для превью, истории чата и подсказки модели. */
  name: string;
  /** MIME-тип из browser File API или fallback application/octet-stream. */
  mimeType: string;
  /** Размер файла в байтах, чтобы показать пользователю понятный вес вложения. */
  size: number;
  /** Тип вложения: image можно отправить vision-модели, file анализируется как текст/метаданные. */
  kind: 'image' | 'file';
  /** Data URL для изображений; обычные файлы не обязаны держать base64 в истории. */
  dataUrl?: string;
  /** Текст файла, если Composer смог прочитать его безопасно. */
  text?: string;
};
